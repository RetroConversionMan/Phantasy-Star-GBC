#!/usr/bin/env python3
"""Native1:1 original32x32 world vehicles from6293/5A94/DB2 and bank18."""
from collections import Counter
import hashlib,json,struct
from PIL import Image,ImageDraw
from extract_scenes import ROOT,SHA,label,cpu_offset
from extract_assets import decode_tile,choose_palettes,color_distance,encode_gb,gbc_color,sms_rgb,c_array

def convert_frames(rom,count=12):
    palette=[0]+list(rom[label('LABEL_DB2'):label('LABEL_DB2')+15])
    raw=rom[label('LABEL_B18_8000'):label('LABEL_B18_8000')+count*512]
    tiles=[decode_tile(raw,n)for n in range(count*16)]
    palettes=choose_palettes([Counter(palette[c]for c in tile if c)for tile in tiles],[1]*len(tiles),8,3)
    colors=struct.pack('<32H',*[gbc_color(c)for p in palettes for c in (0,*p)])
    frames=[]
    # The original layout5 uses source sprite tilesAA..B9 in row-major order.
    ptr=struct.unpack_from('<H',rom,label('LABEL_B03_96F4')+10)[0]
    off=cpu_offset(3,ptr);assert rom[off]==16
    layout=rom[off+1:off+49]
    assert list(layout[17::2])==list(range(0xaa,0xba))
    for frame in range(count):
        gfx=bytearray();meta=bytearray();source=Image.new('RGBA',(32,32));native=source.copy();errors=0
        for q,tile in enumerate(tiles[frame*16:frame*16+16]):
            histogram=Counter(palette[c]for c in tile if c)
            p=min(range(8),key=lambda i:sum(n*min(color_distance(c,v)for v in palettes[i])for c,n in histogram.items()))
            codes=[0 if not c else 1+min(range(3),key=lambda i:color_distance(palette[c],palettes[p][i]))for c in tile]
            gfx.extend(encode_gb(codes));meta.extend((64+(q%4)*8,64+(q//4)*8,q,p|8))
            for n,(c,code)in enumerate(zip(tile,codes)):
                if not c:continue
                x=q%4*8+n%8;y=q//4*8+n//8
                source.putpixel((x,y),(*sms_rgb(palette[c]),255));native.putpixel((x,y),(*sms_rgb(palettes[p][code-1]),255))
                errors+=palette[c]!=palettes[p][code-1]
        frames.append((bytes(gfx+meta)+colors,source,native,errors))
    return frames

def main():
    rom=(ROOT/'upstream/ps1disasm/ps1original.sms').read_bytes();assert hashlib.sha256(rom).hexdigest()==SHA
    out=ROOT/'assets/vehicle-art';out.mkdir(parents=True,exist_ok=True)
    records=[];arrays=[];names=[];sheet=Image.new('RGBA',(4*80,3*100),(32,36,44,255));draw=ImageDraw.Draw(sheet)
    for frame,(data,source,native,errors)in enumerate(convert_frames(rom)):
        name=f'vehicle_frame_{frame:02x}';names.append(name);arrays.append(c_array(name,data))
        (out/f'{frame:02x}.bin').write_bytes(data);source.save(out/f'{frame:02x}-source.png');native.save(out/f'{frame:02x}-gbc.png')
        records.append({'frame':frame,'mode':(frame//4+1)*4,'source_facing':frame%4,'tiles':16,'sprites':16,'quantized_pixels':errors,'data_sha256':hashlib.sha256(data).hexdigest()})
        x=frame%4*80;y=frame//4*100;draw.text((x+2,y+2),str(frame),fill='white');sheet.paste(native.resize((64,64),Image.Resampling.NEAREST),(x,y+20))
    (ROOT/'src/vehicle_art.c').write_text('''/* Generated by tools/extract_vehicle_graphics.py. */
#pragma bank 118
#include <gb/gb.h>
#include "vehicle_art.h"
#include "scene.h"
'''+''.join(arrays)+'static const uint8_t *const frames[12]={'+','.join(names)+'''};
uint8_t vehicle_sprite_load(uint8_t mode,uint8_t facing) __banked {
    static const uint8_t order[4]={2,0,3,1};uint8_t result;
    if((mode!=4u&&mode!=8u&&mode!=12u)||facing>3u)return 0;
    result=scene_actor_show_data(118u,frames[mode-4u+order[facing]],16u,16u);
    scene_actor_active=0;return result;
}
void vehicle_sprite_draw(uint8_t x,uint8_t y) __banked {
    uint8_t i;for(i=0;i<16u;++i)move_sprite(i,x-16u+(i&3u)*8u,y-16u+(i>>2)*8u);
}
''')
    sheet.save(out/'vehicles.png')
    report={'source_sha256':SHA,'native_bank':118,'data_bytes':4608,'records':records,'limits':['Original static directional frames; movement timing controlled by caller','Three-color per-tile quantization with eight shared OBJ palettes; original size and anchor preserved']}
    (out/'manifest.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items()if k!='records'},indent=2))
if __name__=='__main__':main()
