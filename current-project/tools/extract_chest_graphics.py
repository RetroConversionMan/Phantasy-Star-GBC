#!/usr/bin/env python3
"""Original actor0D chest poses, including both source trap sequences."""
import hashlib,json,struct
from PIL import Image,ImageDraw
from extract_scenes import ROOT,SHA,Source,SYMBOLS,label,cpu_offset
from extract_assets import sms_rgb,c_array
from extract_scene_actors import convert

def source_chest(source,frame):
    assert 0x3a<=frame<=0x46
    rom=source.rom;tiles=source.graphics(*SYMBOLS['LABEL_B20_8008'])
    palette=list(rom[label('LABEL_3D1D'):label('LABEL_3D1D')+8])
    palette+=list(rom[label('LABEL_B20_8000'):label('LABEL_B20_8000')+8])
    ptr=struct.unpack_from('<H',rom,label('LABEL_B03_96F4')+frame*2)[0]
    start=cpu_offset(3,ptr);count=rom[start];raw=rom[start+1:start+1+count*3]
    image=Image.new('RGBA',(256,192))
    # Actor0D initializes X=60,Y=58. SMS sprite Y has a one-line offset.
    # Lower OAM indices win, so paint the source list from back to front.
    for n in reversed(range(count)):
        dx,tile=raw[count+n*2:count+n*2+2]
        x=0x60+dx;y=0x58+raw[n]+1
        for pixel,color in enumerate(tiles[tile]):
            sx=(x+pixel%8)&255;sy=(y+pixel//8)&255
            if color and sy<192:image.putpixel((sx,sy),(*sms_rgb(palette[color]),255))
    return image,{'source_sprites':count,'source_metatile_pointer':ptr,'source_bbox':list(image.getbbox())}

def main():
    rom=(ROOT/'upstream/ps1disasm/ps1original.sms').read_bytes()
    assert hashlib.sha256(rom).hexdigest()==SHA
    source=Source(rom);out=ROOT/'assets/chest-art';out.mkdir(parents=True,exist_ok=True)
    records=[];arrays=[];rows=[];total=0
    sheet=Image.new('RGBA',(4*160,4*136),(32,36,44,255));draw=ImageDraw.Draw(sheet)
    for frame in range(0x3a,0x47):
        image,record=source_chest(source,frame)
        gfx,meta,colors,native,errors=convert(image);data=gfx+meta+colors
        symbol=f'chest_frame_{frame:02x}';arrays.append(c_array(symbol,data))
        rows.append(f'{{{len(gfx)//16},{len(meta)//4},{symbol}}}')
        record.update(frame=frame,tiles=len(gfx)//16,sprites=len(meta)//4,quantized_pixels=errors,data_sha256=hashlib.sha256(data).hexdigest())
        (out/f'{frame:02x}.bin').write_bytes(data)
        image.save(out/f'{frame:02x}-source.png');native.save(out/f'{frame:02x}-gbc.png')
        records.append(record);total+=len(data)
        n=frame-0x3a;sheet.paste(native,((n%4)*160,(n//4)*136+16),native)
        draw.text(((n%4)*160+2,(n//4)*136),f'Source pose {frame:02X}',fill='white')
    assert total<15000,total
    (ROOT/'src/chest_art.c').write_text('''/* Generated by tools/extract_chest_graphics.py. */
#pragma bank 115
#include "chest_art.h"
#include "scene.h"
typedef struct { uint8_t tiles,sprites;const uint8_t *data; } ChestFrame;
'''+''.join(arrays)+'static const ChestFrame frames[13]={\n'+',\n'.join(rows)+'''\n};
uint8_t chest_show(uint8_t frame) __banked {
    const ChestFrame *asset;
    if(frame<CHEST_FRAME_CLOSED || frame>0x46u)return 0;
    asset=frames+frame-CHEST_FRAME_CLOSED;
    return scene_actor_show_data(115u,asset->data,asset->tiles,asset->sprites);
}
''')
    sheet.save(out/'poses.png')
    report={'source_sha256':SHA,'native_bank':115,'data_bytes':total,'records':records,
      'limits':['Source-scaled poses, not an implemented source animation scheduler',
                'Native 5/8 scaling and per-tile three-color quantization are explicit adaptations',
                'Screen shake, trap damage, sound and chest rewards belong to caller gameplay']}
    (out/'manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:v for k,v in report.items()if k!='records'},indent=2))
if __name__=='__main__':main()
