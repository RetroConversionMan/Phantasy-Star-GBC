#!/usr/bin/env python3
"""Original physical attack sequences and poses; ordinary visual modes only."""
from collections import Counter
import hashlib,json,struct
from extract_battle_scenes import convert,enemy_palette
from extract_scene_actors import source_overlay
from extract_scenes import ROOT,SHA,Source,label,cpu_offset
from extract_assets import c_array

def main():
 original=(ROOT/'upstream/ps1disasm/ps1original.sms').read_bytes();assert hashlib.sha256(original).hexdigest()==SHA
 rom=bytearray(original);source=Source(rom);out=ROOT/'assets/battle-animation';out.mkdir(parents=True,exist_ok=True)
 patterns=[];pattern_ids={};assets=[];asset_ids={};records=[];enemies=[]
 for enemy in range(1,75):
  if enemy in(72,73):enemies.append(None);continue
  row=rom[label('B03_EnemyData')+enemy*32:label('B03_EnemyData')+(enemy+1)*32];offset=label('LABEL_B03_8FC7')+(row[19]-1)*24;desc=original[offset:offset+24]
  assert desc[0]==15,(enemy,desc[0])
  ptr=struct.unpack_from('<H',desc,9)[0];start=cpu_offset(3,ptr);sequence=[rom[start]];zeros=0
  while zeros<2:
   frame=rom[start+len(sequence)];sequence.append(frame);zeros+=frame==0
   assert len(sequence)<64
  frames=sorted(set(sequence[1:-1])|{desc[1],sequence[0]})
  # Zero is a sequence marker, but visual frame0 can be the real empty-sprite
  # first/reset pose over an opaque source BG fragment.
  if desc[1] and sequence[0]:frames=[f for f in frames if f]
  background=bool(desc[17] and desc[18]);mapping=bytearray()
  for frame in frames:
   rom[offset+1]=frame;indices=[]
   for palette in range(12):
    if palette and not background:indices.append(indices[0]);continue
    image=source_overlay(source,enemy=enemy,palette_index=palette,indexed=True)
    converted,colors,native,errors=convert(image,enemy_palette(source,enemy,palette));meta=bytearray()
    for x,y,pattern,prop in converted:
     if pattern not in pattern_ids:pattern_ids[pattern]=len(patterns);patterns.append(pattern)
     meta.extend(struct.pack('<BBHB',x,y,pattern_ids[pattern],prop))
    data=bytes(meta)+colors;key=(len(converted),data)
    if key not in asset_ids:asset_ids[key]=len(assets);assets.append(key)
    index=asset_ids[key];indices.append(index);name=f'{enemy:02}-{frame:03}-{palette:02}'
    (out/(name+'.bin')).write_bytes(data)
    if palette==0 and enemy in(1,5,49,60,70,74):native.save(out/(name+'.png'))
    records.append({'enemy':enemy,'frame':frame,'palette':palette,'asset':index,'sprites':len(converted),'name':name,'quantized_pixels':errors,'native_sha256':hashlib.sha256(native.tobytes()).hexdigest()})
   mapping.extend(bytes([frame])+struct.pack('<12H',*indices))
  rom[offset:offset+24]=desc
  enemies.append({'enemy':enemy,'descriptor':row[19],'first_frame':desc[1],'speed':desc[8],'sequence':sequence,'frames':frames,'mapping':bytes(mapping)})
  print(f'extracted enemy{enemy}: {len(frames)}frames, {len(assets)}assets, {len(patterns)}pairs',flush=True)
 bins=[];declarations=[]
 def place(name,data):
  slot=next((i for i,b in enumerate(bins) if b['size']+len(data)<=15800),None)
  if slot is None:slot=len(bins);bins.append({'size':0,'parts':[]})
  bins[slot]['size']+=len(data);bins[slot]['parts'].append(c_array(name,data));declarations.append(f'extern const uint8_t {name}[];\n');return 149+slot
 pools=[]
 for start in range(0,len(patterns),256):
  name=f'battle_motion_pairs_{start//256:02}';bank=place(name,b''.join(patterns[start:start+256]));pools.append(f'{{{bank},{name}}}')
 descriptors=[]
 for i,(count,data) in enumerate(assets):
  name=f'battle_motion_asset_{i:04}';bank=place(name,data);descriptors.append(f'{{{bank},{count},{name}}}')
 motions=[]
 for enemy in enemies:
  if enemy is None:motions.append('{0,0,0,0,0,0}');continue
  name=f'battle_motion_sequence_{enemy["enemy"]:02}';bank=place(name,bytes(enemy['sequence'])+enemy['mapping'])
  motions.append(f'{{{enemy["speed"]},{len(enemy["sequence"])},{len(enemy["frames"])},{enemy["first_frame"]},{bank},{name}}}')
 assert len(assets)*4<=15800,('Descriptor bank148 full',len(assets))
 assert len(bins)<=43,('Animation banks exceed149..191',len(bins))
 for old in (ROOT/'src').glob('battle_animation_bank_*.c'):
  if int(old.stem.rsplit('_',1)[1])>=149+len(bins):old.unlink()
 for n,b in enumerate(bins,149):(ROOT/f'src/battle_animation_bank_{n:03}.c').write_text(f'/* Generated original enemy attack poses. */\n#pragma bank {n}\n#include <stdint.h>\n'+''.join(b['parts']))
 (ROOT/'src/battle_animation_data.h').write_text(f'''/* Generated by tools/extract_battle_animation.py. */
#ifndef PS_BATTLE_ANIMATION_DATA_H
#define PS_BATTLE_ANIMATION_DATA_H
#include "battle_scene_data.h"
#define BATTLE_ANIMATION_ASSETS {len(assets)}u
#define BATTLE_ANIMATION_DESCRIPTOR_BANK 148u
typedef struct {{uint8_t speed,length,frames,first_frame,bank;const uint8_t *data;}} BattleAnimation;
extern const BattleAnimation battle_animations[74];
extern const BattleSceneAsset battle_animation_assets[BATTLE_ANIMATION_ASSETS];
extern const BattleScenePool battle_animation_pools[{len(pools)}];
#endif
''')
 (ROOT/'src/battle_animation_data.c').write_text('#ifdef __SDCC\n#pragma bank 31\n#endif\n#include "battle_animation_data.h"\n'+''.join(declarations)+'const BattleAnimation battle_animations[74]={\n'+',\n'.join(motions)+'\n};\nconst BattleScenePool battle_animation_pools[]={'+','.join(pools)+'};\n')
 (ROOT/'src/battle_animation_bank_148.c').write_text('#ifdef __SDCC\n#pragma bank 148\n#endif\n#include "battle_animation_data.h"\n'+''.join(declarations)+'const BattleSceneAsset battle_animation_assets[BATTLE_ANIMATION_ASSETS]={\n'+',\n'.join(descriptors)+'\n};\n')
 (out/'patterns.2bpp').write_bytes(b''.join(patterns))
 report={'source_sha256':SHA,'enemy_obj_palettes':6,'reserved_effect_palettes':[6,7],'native_banks':[148]+list(range(149,149+len(bins))),'bank_bytes':[len(assets)*4]+[b['size'] for b in bins],'pattern_pairs':len(patterns),'unique_assets':len(assets),'records':records,'enemies':[{k:v for k,v in e.items() if k!='mapping'} if e else None for e in enemies],'scope':'Physical-attack source sequences and original frames for enemyIDs1..71,74, all12 floor palettes. Lassic/DarkFalz special handlers and magic/weapon overlays are not included.'}
 (out/'manifest.json').write_text(json.dumps(report,indent=2)+'\n');print(json.dumps({k:v for k,v in report.items() if k not in('records','enemies')},indent=2))
if __name__=='__main__':main()
