#!/usr/bin/env python3
"""Extract authentic RPG tables from the byte-identical SMS reference build."""
import argparse, hashlib, json, re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SHA='9e324e92bd833b45126861b6f1d2dcbb51251bdf3df6d563ab3a3ff784d8cf88'
# Resolved locations from build/sms-reference/ps1built.sym, checked against source.
LOCATIONS={
 'levels':(3,0xb8af,4*30*8), 'enemies':(3,0x867f,75*32),
 'shops':(3,0xb70d,29*10), 'sell_prices':(3,0xb82f,64*2), 'equip_boost':(0,0x183a,64),
 'item_flags':(1,0x7fab,64), 'spell_cost':(0,0x1ddc,19),
 'battle_spells':(0,0x1a57,15), 'map_spells':(0,0x1def,15),
 'encounter_pools':(3,0x8180,0x8470-0x8180),
 'map_encounters':(3,0x8470,0x85a0-0x8470),
 'terrain_encounters':(3,0x85a0,0x867f-0x85a0),
 'world_regions':(3,0x8000,0x180),
 'terrain_lookup':(3,0x85a0,256),
 'map_encounter_window':(3,0x8470,94*16),
 'dungeon_settings':(3,0xb619,61*4),
}

def extract(rom,bank,addr,size):
    offset=bank*0x4000+(addr&0x3fff)
    result=rom[offset:offset+size]
    assert len(result)==size
    return result

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--rom',type=Path,default=ROOT/'upstream/ps1disasm/ps1original.sms')
    a=p.parse_args(); rom=a.rom.read_bytes()
    assert hashlib.sha256(rom).hexdigest()==SHA,'Unexpected source ROM; verify offsets before conversion'
    tables={k:extract(rom,*v) for k,v in LOCATIONS.items()}
    assert tables['levels'][:8]==bytes([16,8,8,0,0,0,0,0])
    assert tables['enemies'][32:37]==b'SWORM'
    assert tables['enemies'][32+21:32+24]==bytes([8,13,9])
    assert len(tables['encounter_pools'])%8==0
    assert max(tables['terrain_lookup'])+10 < 94
    assert max(tables['world_regions'][1::2]) < 16
    constants=[]
    for line in (ROOT/'upstream/ps1disasm/ps1.constants.asm').read_text().splitlines():
        m=re.match(r'\.define\s+((?:ItemID|MagicID|EnemyID)_\w+)\s+(\$[0-9A-Fa-f]+|\d+)\b',line)
        if m:
            v=int(m[2][1:],16) if m[2].startswith('$') else int(m[2])
            constants.append(f'#define {m[1]} {v}u')
    h=['/* Generated by tools/extract_rpg.py; authentic SMS tables in ROM bank 4. */',
       '#ifndef PS_RPG_DATA_H','#define PS_RPG_DATA_H','#include <stdint.h>',
       '#define RPG_ENEMY_COUNT 75u','#define RPG_SHOP_COUNT 29u',
       f'#define RPG_ENCOUNTER_POOL_COUNT {len(tables["encounter_pools"])//8}u',
       '#define RPG_DATA_BANK 4u']+constants
    c=['/* Generated from source ROM SHA-256 '+SHA+'. */',
       '#ifdef __SDCC','#pragma bank 4','#endif','#include "rpg_data.h"']
    dims={'levels':'[4][30][8]','enemies':'[75][32]','shops':'[29][10]',
          'sell_prices':'[64][2]', 'battle_spells':'[3][5]','map_spells':'[3][5]',
          'encounter_pools':f'[{len(tables["encounter_pools"])//8}][8]',
          'map_encounters':'[19][16]','world_regions':'[3][64][2]',
          'map_encounter_window':'[94][16]', 'dungeon_settings':'[61][4]'}
    def nested(data,shape):
        if len(shape)==1:return '{'+','.join(f'0x{x:02x}' for x in data)+'}'
        stride=len(data)//shape[0]
        return '{\n'+',\n'.join(nested(data[i*stride:(i+1)*stride],shape[1:]) for i in range(shape[0]))+'\n}'
    for k,data in tables.items():
        d=dims.get(k,f'[{len(data)}]')
        h.append(f'extern const uint8_t rpg_{k}{d};')
        shape=[int(n) for n in re.findall(r'\d+',d)]
        assert __import__('math').prod(shape)==len(data),(k,shape,len(data))
        c.append(f'const uint8_t rpg_{k}{d} = '+nested(data,shape)+';')
    # Enemy display names copied literally, with the original text terminator replaced by NUL.
    names=[]
    for i in range(75):
        raw=tables['enemies'][i*32:i*32+8]
        text=raw.split(bytes([0x65]))[0].decode('ascii',errors='replace').rstrip()
        if i==0:text='NONE'
        names.append(text)
    h+=['extern const char rpg_enemy_names[75][9];','#endif']
    c.append('const char rpg_enemy_names[75][9] = {\n'+',\n'.join(json.dumps(s) for s in names)+'\n};')
    (ROOT/'src/rpg_data.h').write_text('\n'.join(h)+'\n')
    (ROOT/'src/rpg_data.c').write_text('\n'.join(c)+'\n')
    report={'source_sha256':SHA,'tables':{k:{'bank':v[0],'address':hex(v[1]),'bytes':v[2],'sha256':hashlib.sha256(tables[k]).hexdigest()} for k,v in LOCATIONS.items()}}
    (ROOT/'build/rpg_extraction.json').write_text(json.dumps(report,indent=2)+'\n')
    print(f'Extracted {sum(map(len,tables.values()))} authentic table bytes, 75 enemies, 120 level records and 29 shops.')
if __name__=='__main__':main()
