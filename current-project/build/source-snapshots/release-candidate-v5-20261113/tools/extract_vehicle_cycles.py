#!/usr/bin/env python3
"""Source vehicle sprites with separate static and cycling color-index layers.

Original7C18 rotates13..15 for land/ice and7..9 for Hovercraft. Equal initial
RGB values cannot be merged across these classes. Two disjoint OBJ layers keep
all cycling pixels exact without animating static lookalike colors.
"""
from pathlib import Path
from collections import Counter
import argparse,hashlib,json,struct,sys
ROOT=next(p for p in Path(__file__).resolve().parents if(p/'upstream/ps1disasm/ps1original.sms').exists())
PROJECT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'tools'))
from extract_assets import ROM_SHA256,decode_tile,choose_palettes,DIST,encode_gb,gbc_color,c_array
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--rom',type=Path,default=ROOT/'upstream/ps1disasm/ps1original.sms');p.add_argument('--src',type=Path,default=PROJECT/'src');p.add_argument('--output',type=Path,default=PROJECT/'assets/vehicle-cycles');args=p.parse_args()
 args.src.mkdir(parents=True,exist_ok=True);args.output.mkdir(parents=True,exist_ok=True)
 rom=args.rom.read_bytes();assert hashlib.sha256(rom).hexdigest()==ROM_SHA256
 palette=bytes([0])+rom[0xdb2:0xdc1];assert len(palette)==16
 all_tiles=[[decode_tile(rom[18*16384+f*512:][:512],q)for q in range(16)]for f in range(12)]
 def animated(f):return(7,8,9)if 4<=f<8 else(13,14,15)
 hist=[Counter(palette[c]for c in t if c and c not in animated(f))for f,tiles in enumerate(all_tiles)for t in tiles]
 pals=choose_palettes(hist,[1]*len(hist),7,3)
 fixed=struct.pack('<28H',*[gbc_color(c)for pal in pals for c in(0,*pal)])
 arrays=[];names=[];records=[];counts=[]
 for f,tiles in enumerate(all_tiles):
  dynamic=animated(f);base=bytearray();over=bytearray();meta=bytearray();overlay_meta=bytearray();quantized=0;cycle_pixels=0
  for q,t in enumerate(tiles):
   h=Counter(palette[c]for c in t if c and c not in dynamic)
   pid=min(range(7),key=lambda i:sum(n*min(DIST[c][v]for v in pals[i])for c,n in h.items()))
   codes=[0 if not c or c in dynamic else 1+min(range(3),key=lambda i:DIST[palette[c]][pals[pid][i]])for c in t]
   base+=encode_gb(codes);meta+=bytes((64+(q&3)*8,64+(q>>2)*8,q,8|pid))
   quantized+=sum(bool(c)and c not in dynamic and palette[c]!=pals[pid][v-1]for c,v in zip(t,codes))
   if any(c in dynamic for c in t):
    index=16+len(over)//16;over+=encode_gb([dynamic.index(c)+1 if c in dynamic else 0 for c in t])
    overlay_meta+=bytes((64+(q&3)*8,64+(q>>2)*8,index,15))
    cycle_pixels+=sum(c in dynamic for c in t)
  count=16+len(over)//16;assert count<=32;counts.append(count)
  data=base+over+meta+overlay_meta+fixed+struct.pack('<4H',0,*[gbc_color(palette[c])for c in dynamic])
  name=f'vehicle_cycle_frame_{f:02x}';names.append(name);arrays.append(c_array(name,data));(args.output/f'{f:02x}.bin').write_bytes(data)
  records.append(dict(frame=f,mode=(f//4+1)*4,source_facing=f%4,sprites=count,tiles=count,animated_indices=dynamic,cycling_pixels=cycle_pixels,quantized_static_pixels=quantized,sha256=hashlib.sha256(data).hexdigest()))
 palettes=[]
 for table in(0x7c6d,0x7c73):
  for phase in range(3):palettes.extend([0]+[gbc_color(v)for v in rom[table+phase:table+phase+3]])
 c='''/* Generated by tools/extract_vehicle_cycles.py; original7C18 index classes. */
#pragma bank 118
#include <gb/gb.h>
#include <gb/cgb.h>
#include "vehicle_art.h"
#include "scene.h"
'''+''.join(arrays)+c_array('vehicle_cycle_palettes',palettes,'uint16_t')+'static const uint8_t *const frames[12]={'+','.join(names)+'};\n'+c_array('vehicle_cycle_counts',counts)+'''
static uint8_t loaded_frame,displayed_cycle;
void vehicle_palette_reset(void) __banked {displayed_cycle=0;}
void vehicle_palette_cycle(uint8_t mode,uint8_t phase) __banked {
    displayed_cycle=phase+1u;
    set_sprite_palette(7u,1u,vehicle_cycle_palettes+(mode==8u?12u:0u)+phase*4u);
}
uint8_t vehicle_sprite_load(uint8_t mode,uint8_t facing) __banked {
    static const uint8_t order[4]={2,0,3,1};uint8_t result,count;
    if((mode!=4u&&mode!=8u&&mode!=12u)||facing>3u)return 0;
    loaded_frame=mode-4u+order[facing];count=vehicle_cycle_counts[loaded_frame];
    result=scene_actor_show_data(118u,frames[loaded_frame],count,count);
    if(displayed_cycle)vehicle_palette_cycle(mode,displayed_cycle-1u);
    scene_actor_active=0;return result;
}
void vehicle_sprite_draw(uint8_t x,uint8_t y) __banked {
    uint8_t i,count=vehicle_cycle_counts[loaded_frame];
    const uint8_t *meta=frames[loaded_frame]+(uint16_t)count*16u;
    for(i=0;i<count;++i){move_sprite(i,x-80u+meta[0],y-80u+meta[1]);meta+=4;}
    for(;i<40u;++i)move_sprite(i,0,0);
}
'''
 (args.src/'vehicle_art.c').write_text(c)
 (args.output/'manifest.json').write_text(json.dumps(dict(source_sha256=ROM_SHA256,records=records,static_palettes_sms=pals,limits=['Static pixels use7 shared GBC palettes with3 opaque colors; source cycling indices use exact separate palette7.','Two disjoint layers add sprites without altering original alpha, coordinates or cycling ownership. Maximum8 sprites per scanline.']),indent=2)+'\n')
 print(json.dumps(dict(records=len(records),counts=counts,cycling_pixels=sum(r['cycling_pixels']for r in records),static_quantized=sum(r['quantized_static_pixels']for r in records))))
if __name__=='__main__':main()
